package fork.MaxrregMustermann.TheFileManager.filelist

import android.os.AsyncTask
import java8.nio.file.DirectoryIteratorException
import java8.nio.file.Path
import fork.MaxrregMustermann.TheFileManager.file.FileItem
import fork.MaxrregMustermann.TheFileManager.file.loadFileItem
import fork.MaxrregMustermann.TheFileManager.provider.common.newDirectoryStream
import fork.MaxrregMustermann.TheFileManager.search.SearchIndexer
import fork.MaxrregMustermann.TheFileManager.util.CloseableLiveData
import fork.MaxrregMustermann.TheFileManager.util.Failure
import fork.MaxrregMustermann.TheFileManager.util.Loading
import fork.MaxrregMustermann.TheFileManager.util.Stateful
import fork.MaxrregMustermann.TheFileManager.util.Success
import fork.MaxrregMustermann.TheFileManager.util.valueCompat
import java.io.IOException
import java.util.concurrent.ExecutorService
import java.util.concurrent.Future

class FileListLiveData(private val path: Path) : CloseableLiveData<Stateful<List<FileItem>>>() {
    private var future: Future<Unit>? = null

    private val observer: PathObserver

    @Volatile
    private var isChangedWhileInactive = false

    init {
        loadValue()
        observer = PathObserver(path) { onChangeObserved() }
    }

    fun loadValue() {
        future?.cancel(true)
        value = Loading(value?.value)
        future = (AsyncTask.THREAD_POOL_EXECUTOR as ExecutorService).submit<Unit> {
            val value = try {
                path.newDirectoryStream().use { directoryStream ->
                    val fileList = mutableListOf<FileItem>()
                    for (path in directoryStream) {
                        try {
                            fileList.add(path.loadFileItem())
                        } catch (e: DirectoryIteratorException) {
                            // TODO: Ignoring such a file can be misleading and we need to support
                            //  files without information.
                            e.printStackTrace()
                        } catch (e: IOException) {
                            e.printStackTrace()
                        }
                    }
                    Success(fileList as List<FileItem>)
                }
            } catch (e: Exception) {
                Failure(valueCompat.value, e)
            }
            // Indexing the directory that was just listed is nearly free, because the listing
            // already read everything needed to do it, and it is what makes a later search below
            // this directory instant.
            SearchIndexer.indexDirectory(path)
            postValue(value)
        }
    }

    private fun onChangeObserved() {
        if (hasActiveObservers()) {
            loadValue()
        } else {
            isChangedWhileInactive = true
        }
    }

    override fun onActive() {
        if (isChangedWhileInactive) {
            loadValue()
            isChangedWhileInactive = false
        }
    }

    override fun close() {
        observer.close()
        future?.cancel(true)
    }
}
